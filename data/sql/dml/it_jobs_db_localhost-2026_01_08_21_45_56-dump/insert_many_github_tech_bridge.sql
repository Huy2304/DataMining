INSERT INTO TECH_META (TECH_NAME, CATEGORY)
SELECT DISTINCT PRLANG_NAME, 'language'
FROM GITHUB_REPO_PRLANGS
ON CONFLICT (TECH_NAME) DO NOTHING;

INSERT INTO GITHUB_REPO_TECH_BRIDGE (REPO_META_ID, TECH_NAME)
SELECT m.REPO_META_ID, p.PRLANG_NAME
FROM GITHUB_REPO_PRLANGS p
JOIN GITHUB_REPO_META m ON p.REPO_ID = m.REPO_ID
ON CONFLICT (REPO_META_ID, TECH_NAME) DO NOTHING;

INSERT INTO TECH_META (TECH_NAME, CATEGORY)
SELECT DISTINCT TOPIC_NAME, 'topic'
FROM GITHUB_REPO_TOPICS
ON CONFLICT (TECH_NAME) DO NOTHING;

INSERT INTO GITHUB_REPO_TECH_BRIDGE (REPO_META_ID, TECH_NAME)
SELECT m.REPO_META_ID, t.TOPIC_NAME
FROM GITHUB_REPO_TOPICS t
JOIN GITHUB_REPO_META m ON t.REPO_ID = m.REPO_ID
ON CONFLICT (REPO_META_ID, TECH_NAME) DO NOTHING;
