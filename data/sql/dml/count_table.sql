SELECT
    (SELECT COUNT(*) FROM GITHUB_REPO_COMMITS)       AS GITHUB_REPO_COMMITS_COUNT,
    (SELECT COUNT(*) FROM GITHUB_REPO_META)          AS GITHUB_REPO_META_COUNT,
    (SELECT COUNT(*) FROM GITHUB_REPO_PRLANGS)       AS GITHUB_REPO_PRLANGS_COUNT,
    (SELECT COUNT(*) FROM GITHUB_REPO_TECH_BRIDGE)   AS GITHUB_REPO_TECH_BRIDGE_COUNT,
    (SELECT COUNT(*) FROM GITHUB_REPO_TOPICS)        AS GITHUB_REPO_TOPICS_COUNT,
    (SELECT COUNT(*) FROM IT_JOBS_ANALYSIS)          AS IT_JOBS_ANALYSIS_COUNT,
    (SELECT COUNT(*) FROM JOB_TECH_BRIDGE)           AS JOB_TECH_BRIDGE_COUNT,
    (SELECT COUNT(*) FROM STACKOVERFLOW_POSTS)       AS STACKOVERFLOW_POSTS_COUNT,
    (SELECT COUNT(*) FROM STACKOVERFLOW_TECH_BRIDGE) AS STACKOVERFLOW_TECH_BRIDGE_COUNT;

