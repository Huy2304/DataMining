CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ===================================================================================================
-- MAIN TABLE
-- ===================================================================================================
CREATE TABLE IF NOT EXISTS TECH_META (
    TECH_NAME TEXT PRIMARY KEY,          -- 'java,spring boot'
    CATEGORY TEXT,                       -- 'language', 'framework', 'database', 'tool'
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS IT_JOBS_ANALYSIS (
    ID UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    JOB_TITLE TEXT,
    COMPANY TEXT,
    -- LANGUAGE TEXT,
    -- TECHNOLOGIES TEXT,
    DATE_POSTED DATE,
    SUBFIELD TEXT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS STACKOVERFLOW_POSTS (
    ID UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    SO_ID BIGINT UNIQUE,
    TITLE TEXT,
    VIEW_COUNT INT DEFAULT 0,
    ANSWER_COUNT INT DEFAULT 0,
    SCORE INT DEFAULT 0,
    DATE_POSTED DATE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE GITHUB_REPO_META (
    REPO_META_ID UUID PRIMARY KEY DEFAULT gen_random_uuid()
    REPO_ID INT NOT NULL,
    -- REPO_OWNER VARCHAR(100) NOT NULL,
    -- REPO_OWNER_TYPE VARCHAR(100) NOT NULL,
    -- REPO_NAME VARCHAR(100) NOT NULL,
    -- REPO_DESC VARCHAR(200) NOT NULL,
    REPO_CREATED_AT VARCHAR(100) NOT NULL,
    REPO_UPDATED_AT VARCHAR(100) NOT NULL,
    REPO_PUSHED_AT VARCHAR(100) NOT NULL,
    REPO_SIZE_COUNT INT NOT NULL,
    REPO_STARS_COUNT INT NOT NULL,
    REPO_WATCHERS_COUNT INT NOT NULL,
    REPO_FORKS_COUNT INT NOT NULL,
    REPO_OPEN_ISSUES_COUNT INT NOT NULL,
    REPO_DEFAULT_BRANCH VARCHAR(100) NOT NULL,
    REPO_LICENSE VARCHAR(100),
    PRIMARY KEY (REPO_META_ID)
);

CREATE TABLE GITHUB_REPO_PRLANGS (
    REPO_PRLANGS_ID SERIAL,
    REPO_ID INT NOT NULL,
    PRLANG_NAME VARCHAR(20) NOT NULL,
    PRLANG_BYTE_COUNT INT NOT NULL,
    PRIMARY KEY(REPO_PRLANGS_ID),
    FOREIGN KEY (REPO_ID) REFERENCES GITHUB_REPO_META(REPO_ID)
);

CREATE TABLE GITHUB_REPO_COMMITS (
    REPO_COMMITS_ID SERIAL,
    REPO_ID INT NOT NULL,
    COMMIT_SHA VARCHAR(100) NOT NULL,
    -- COMMIT_MESSAGE VARCHAR(200) NOT NULL,
    -- COMMIT_AUTHOR VARCHAR(100) NOT NULL,
    -- COMMIT_AUTHOR_EMAIL VARCHAR(100) NOT NULL,
    COMMIT_AUTHOR_DATE VARCHAR(100) NOT NULL,
    -- COMMIT_COMMITTER VARCHAR(100) NOT NULL,
    -- COMMIT_COMMITTER_EMAIL VARCHAR(100) NOT NULL,
    COMMIT_COMMITTER_DATE VARCHAR(100) NOT NULL,
    COMMIT_PARENT_SHA VARCHAR(100),
    PRIMARY KEY (REPO_COMMITS_ID),
    FOREIGN KEY (REPO_ID) REFERENCES GITHUB_REPO_META(REPO_ID)
);

CREATE TABLE GITHUB_REPO_TOPICS (
    REPO_TOPICS_ID SERIAL,
    REPO_ID INT NOT NULL,
    TOPIC_NAME VARCHAR(100) NOT NULL,
    PRIMARY KEY (REPO_TOPICS_ID),
    FOREIGN KEY (REPO_ID) REFERENCES GITHUB_REPO_META(REPO_ID)
);

